def relay_configuration(values: dict[str, Any]) -> str:
    if set(values) != {"username", "credential"}:
        raise ServiceError("invalid_submission_settings", 400)
    # Provider-issued ASCII credentials only. No configuration macros or escapes.
    for field, limit in (("username", 256), ("credential", 4096)):
        value = values[field]
        if not isinstance(value, str) or not 1 <= len(value) <= limit or not re.fullmatch(
            r"[A-Za-z0-9@._+:/=\-]+", value
        ):
            raise ServiceError("invalid_submission_credential", 400)
    return (
        'target.smtp submission_relay {\n'
        '    targets tcp://smtp-relay.brevo.com:587\n'
        '    starttls yes\n'
        f'    auth plain "{values["username"]}" "{values["credential"]}"\n'
        '    connect_timeout 15s\n    command_timeout 30s\n'
        '    submission_timeout 2m\n}\n'
    )
