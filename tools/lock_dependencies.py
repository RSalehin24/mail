"""Generate hashed pip locks from pip's resolver report and PyPI distribution hashes."""

import argparse
import json
import urllib.request
from pathlib import Path


def requirement(record: dict[str, object]) -> str:
    metadata = record["metadata"]
    if not isinstance(metadata, dict):
        raise ValueError("Resolver metadata missing")
    name, version = metadata["name"], metadata["version"]
    with urllib.request.urlopen(
        f"https://pypi.org/pypi/{name}/{version}/json", timeout=30
    ) as reply:
        release = json.load(reply)
    hashes = sorted({entry["digests"]["sha256"] for entry in release["urls"]})
    if not hashes:
        raise ValueError("No distributions")
    return f"{name}=={version}" + "".join(" \\\n    --hash=sha256:" + digest for digest in hashes)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    resolution = json.loads(arguments.report.read_text())
    records = sorted(resolution["install"], key=lambda item: item["metadata"]["name"].lower())
    content = "# Generated by tools/lock_dependencies.py from pip resolution.\n"
    arguments.output.write_text(content + "\n".join(map(requirement, records)) + "\n")


if __name__ == "__main__":
    main()
