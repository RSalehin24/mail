// Exercise the actual TypeScript request scheduler with controlled fetch latency.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
globalThis.window = new EventTarget();
const code = await readFile(new URL('../build/read-tests/api.js', import.meta.url), 'utf8');
const { api, cached, clearSessionData, ApiError, errorMessage } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const requests = [];
globalThis.fetch = (url, options) => new Promise((resolve, reject) => {
  const item = { url, finish: () => resolve({ ok: true, json: async () => ({ url, observed_at: 123 }) }) };
  requests.push(item);
  options.signal?.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')), { once: true });
});
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const slow = api('/diagnostics');
const duplicate = api('/diagnostics');
const accounts = api('/accounts');
const provider = api('/settings/relay');
const queued = api('/other');
const telemetry = api('/telemetry');
await tick();
assert.equal(requests.length, 3, 'Two primary reads and reserved telemetry slot');
requests.find(item => item.url === '/api/accounts').finish();
await accounts; await tick();
assert.equal(requests.length, 4);
assert.deepEqual(cached('/accounts'), { url: '/api/accounts', observed_at: 123 });
requests.find(item => item.url === '/api/telemetry').finish();
await telemetry;
assert.equal(requests.filter(item => item.url === '/api/diagnostics').length, 1);
requests.find(item => item.url === '/api/diagnostics').finish();
assert.deepEqual(await slow, await duplicate);
const remaining = Promise.allSettled([provider, queued]);
clearSessionData();
assert.equal(cached('/accounts'), undefined);
assert.ok((await remaining).every(item => item.status === 'rejected'));
console.log('PASS: bounded reads, duplicate sharing, independent telemetry, original timestamps, session cancellation');

const diagnosticId = 'd4970d8d-d0f9-4288-905e-89ff4ae646bb';
const displayError = new ApiError('invalid_master_password', 401, diagnosticId);
assert.equal(displayError.message, 'Invalid master password.');
assert.equal(displayError.requestId, diagnosticId, 'Diagnostic IDs remain available internally');
assert.equal(errorMessage('backup_integrity_failed'), 'Backup integrity failed.');
globalThis.fetch = async () => ({ok: false, status: 401, json: async () => ({error: 'authentication_failed', request_id: diagnosticId})});
await assert.rejects(api('/security/reauth', {password: 'wrong'}), error => error.code === 'authentication_failed' && error.message === 'Invalid master password.' && error.requestId === diagnosticId);
await assert.rejects(api('/security/reauth/verify', {code: 'wrong'}), error => error.message === 'Invalid verification code.');
const formatCode = await readFile(new URL('../build/read-tests/format.js', import.meta.url), 'utf8');
const { formatDate } = await import(`data:text/javascript;base64,${Buffer.from(formatCode).toString('base64')}`);
assert.equal(formatDate('2026-08-10T03:00:00Z'), 'Aug 10, 2026');
assert.equal(formatDate('2026-08-09T18:00:00Z'), 'Aug 10, 2026', 'Dates use the Dhaka calendar');
console.log('PASS: friendly errors without visible diagnostic IDs, authentication context, consistent dates');
