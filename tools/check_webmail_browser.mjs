import assert from 'node:assert/strict';
import { spawn, execFileSync } from 'node:child_process';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { connect } from './browser_connection.mjs';

const material = JSON.parse(execFileSync('docker', ['exec', 'mail-admin-webmail-ui-test', 'python', '-c', 'from pathlib import Path; print(Path("/fixture/browser.json").read_text())'], { encoding: 'utf8' }));
const profile = await mkdtemp(`${tmpdir()}/webmail-browser-`);
const chrome = spawn(process.env.MAIL_ADMIN_CHROME || '/opt/google/chrome/chrome', ['--headless', '--remote-debugging-port=0', `--user-data-dir=${profile}`, '--no-first-run', '--disable-background-networking', '--disable-sync', 'about:blank'], { stdio: 'ignore' });
const draftSubject = `Browser draft ${Date.now()}`;
const labelName = `Browser label ${Date.now()}`;
const report = { scope: 'Synthetic webmail with real Maddy 0.9.6; loopback HTTP browser, verified TLS IMAP/SMTP', result: 'fail', cases: [] };
let connection;
try {
  connection = await connect(profile);
  await connection.call('Page.enable');
  await connection.call('Network.enable');
  const external = [];
  connection.events.set('Network.requestWillBeSent', event => { if (/tracker\.invalid/.test(event.request.url)) external.push(event.request.url); });
  await connection.call('Page.navigate', { url: `http://localhost:${material.web_port}` });
  await connection.until(`document.querySelector('h1')?.textContent === 'Welcome back'`);
  await connection.fill('Email address', material.email);
  await connection.fill('Password', material.password);
  await connection.click({ tag: 'button', name: 'Continue securely' });
  await connection.until(`document.querySelector('h1')?.textContent === 'Your mail'`);
  await connection.until(`document.querySelector('[aria-label="Messages"]') !== null`);
  assert.equal(await connection.read(`document.body.textContent.includes('Outgoing mail provider')`), false);
  for (const width of [360, 768, 1280]) {
    await connection.call('Emulation.setDeviceMetricsOverride', { width, height: 1000, deviceScaleFactor: 1, mobile: false });
    assert.equal(await connection.read('document.documentElement.scrollWidth <= innerWidth'), true, `No overflow at ${width}`);
    await connection.screenshot(`webmail-inbox-${width}`);
  }
  report.cases.push('mailbox login, role-specific navigation, 360/768/1280 layouts');
  await connection.click({ tag: '[role=button]', name: 'Open Synthetic attachment and HTML' });
  await connection.until(`document.querySelector('iframe[title="Email message content"]') !== null`);
  assert.equal(await connection.read(`document.querySelector('iframe').getAttribute('sandbox').includes('allow-scripts') || document.querySelector('iframe').getAttribute('sandbox').includes('allow-same-origin')`), false);
  assert.equal(external.length, 0);
  assert.equal(await connection.read(`document.querySelector('iframe').srcdoc.includes('<script')`), false);
  assert.equal(await connection.read(`document.body.textContent.includes('attack')`), false);
  report.cases.push('hostile HTML isolated, scripts removed, remote image not requested');
  await connection.click({ tag: 'button', name: 'Reply all' });
  await connection.until(`document.querySelector('[role=dialog] textarea') !== null`);
  assert.equal(await connection.read(`document.querySelector('[role=dialog]').textContent.includes(${JSON.stringify(material.email)})`), true);
  await connection.fill('Subject', draftSubject);
  await connection.fill('Message', 'Synthetic saved draft from the browser.');
  await connection.click({ tag: 'button', name: 'Save draft' });
  await connection.until(`document.querySelector('[role=dialog]')?.textContent.includes('Saved on server')`);
  await connection.click({ tag: 'button', name: 'Close' });
  await connection.read(`[...document.querySelectorAll('[aria-label="Mail folders"] [role=button]')].find(element => element.textContent.startsWith('Drafts')).click()`);
  await connection.until(`document.body.textContent.includes(${JSON.stringify(draftSubject)}) && !document.querySelector('[role=progressbar]')`);
  await connection.click({ tag: '[role=button]', name: `Open ${draftSubject}` });
  await connection.until(`document.body.textContent.includes('Edit draft')`);
  await connection.click({ tag: 'button', name: 'Edit draft' });
  await connection.until(`document.querySelector('[role=dialog] textarea')?.value.includes('Synthetic saved draft')`);
  await connection.fill('To', 'webmail-load-01@rsalehin24.me');
  await connection.click({ tag: 'button', name: 'Send' });
  await connection.until(`document.querySelector('[role=dialog]')?.textContent.includes('Submitted to Maddy and saved to Sent')`);
  await connection.click({ tag: 'button', name: 'Close' });
  report.cases.push('reply-all, server draft save/reopen, submission and Sent status');
  await connection.click({ tag: 'button', name: 'Create label' });
  await connection.fill('Label name', labelName);
  await connection.until(`[...document.querySelectorAll('[role=dialog] button')].some(button => button.textContent === 'Save' && !button.disabled)`);
  await connection.click({ tag: 'button', name: 'Save' });
  await connection.until(`document.querySelector('[role=dialog]') === null && document.body.textContent.includes(${JSON.stringify(labelName)})`);
  await connection.read(`[...document.querySelectorAll('button')].find(element => element.textContent === 'Profile').click()`);
  await connection.until(`document.querySelector('h1')?.textContent === 'Your profile'`);
  await connection.fill('Display name', 'Browser Profile');
  await connection.fill('Plain-text signature', 'A plain signature');
  await connection.click({ tag: 'button', name: 'Save profile' });
  await connection.until(`document.body.textContent.includes('Profile saved.')`);
  await connection.call('Page.reload');
  await connection.until(`document.querySelector('h1')?.textContent === 'Your profile'`);
  assert.equal(await connection.read(`[...document.querySelectorAll('input')].find(input => input.labels?.[0]?.textContent === 'Display name').value`), 'Browser Profile');
  assert.equal(await connection.read(`[...document.querySelectorAll('input')].find(input => input.labels?.[0]?.textContent === 'Mailbox address').readOnly`), true);
  assert.equal(await connection.read('localStorage.length + sessionStorage.length'), 0);
  report.cases.push('label creation, persistent private profile, read-only address, no browser storage');
  await connection.click({ tag: 'button', name: 'Sign out' });
  await connection.until(`document.querySelector('h1')?.textContent === 'Welcome back'`);
  report.cases.push('sign-out clears mailbox UI');
  report.result = 'pass';
} catch (error) {
  report.reason = error.message;
  process.exitCode = 1;
  if (connection) await connection.screenshot('webmail-browser-failure');
  console.error(error.stack);
} finally {
  connection?.socket.close();
  chrome.kill('SIGTERM');
  await new Promise(resolve => chrome.once('exit', resolve));
  await rm(profile, { recursive: true, force: true });
  await writeFile(resolve('build/webmail-browser.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
}
