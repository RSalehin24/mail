def check_dag(graph):
    require(all(set(dependencies) <= set(graph) for dependencies in graph.values()),
            'Dependency references an unknown node')
    pending = dict(graph)
    complete = set()
    while pending:
        ready = {name for name, dependencies in pending.items() if set(dependencies) <= complete}
        require(bool(ready), 'Dependency cycle detected')
        complete.update(ready)
        pending = {name: dependencies for name, dependencies in pending.items() if name not in ready}


def catalogue_text(catalogue):
    result = ['# Acceptance catalogue', '',
              'Generated by verify_plan.py from [test-catalog.json](test-catalog.json). Do not hand-edit.', '',
              'Every case is pending until executed against the qualified release artifacts. '
              'T groups run in isolation; P groups require operator-approved target checks.', '']
    for group in catalogue['groups']:
        result.extend(['## ' + group['id'], '', '**' + group['title'] + '**', '',
                       'Required environment: `' + group['environment'] + '`.', '', group['contract'], ''])
        result.extend('- **' + case['id'] + '**: ' + case['expected'] for case in group['cases'])
        result.append('')
    return '\n'.join(result)


def validate_catalogue(root, catalogue):
    groups = indexed(catalogue['groups'])
    expected = {'T' + str(number).zfill(2) for number in range(1, 23)}
    expected.update('P' + str(number).zfill(2) for number in range(1, 9))
    require(set(groups) == expected, 'Unexpected acceptance group coverage')
    for identifier, group in groups.items():
        cases = indexed(group['cases'])
        require(bool(cases), 'Test group has no cases')
        require(all(case.startswith(identifier + '.') for case in cases), 'Case/group ID mismatch')
        require(all(isinstance(case.get('expected'), str) and case['expected'].strip()
                    for case in cases.values()), 'Case lacks an expected behavior')
    generated = root / 'verification/acceptance.md'
    require(generated.read_text() == catalogue_text(catalogue), 'Generated acceptance catalogue is stale')
    return groups


def validate_requirements(root, contract, groups):
    requirements = indexed(contract['requirements'])
    expected = {'R' + str(number).zfill(2) for number in range(1, 23)}
    require(set(requirements) == expected, 'Unexpected requirement coverage')
    gates = indexed(contract['gates'])
    for record in requirements.values():
        require(bool(record['tests']) and set(record['tests']) <= set(groups), 'Unmapped requirement test')
        require(bool(record['gates']) and set(record['gates']) <= set(gates), 'Unmapped requirement gate')
        require((root / record['document']).is_file(), 'Missing requirement design document')
    mapped = {test for record in requirements.values() for test in record['tests']}
    require(set(groups) <= mapped, 'Acceptance group has no requirement owner')
    check_dag({identifier: gate['depends_on'] for identifier, gate in gates.items()})
    check_dag(contract['work_packages'])
    return len(requirements)


def validate_work_package_table(root, contract):
    text = (root / 'implementation/work-packages.md').read_text()
    rows = re.findall(r'^\| (W\d{2}) [^|]+\| ([^|]+)\|', text, re.M)
    declared = {identifier: re.findall(r'W\d{2}', dependencies)
                for identifier, dependencies in rows}
    require(declared == contract['work_packages'], 'Work-package table and dependency graph differ')


def validate_rollout(root, contract):
    text = (root / 'operations/rollout.md').read_text()
    phases = [int(number) for number in re.findall(r'^(\d+)\. \*\*', text, re.M)]
    require(phases == list(range(1, 10)) and text.count('**Gate:**') == 8,
            'Rollout phases or forward gates are incomplete')
    expected = {'G' + str(number).zfill(2): [] if number == 1 else ['G' + str(number - 1).zfill(2)]
                for number in range(1, 9)}
    actual = {gate['id']: gate['depends_on'] for gate in contract['gates']}
    require(actual == expected, 'Forward gates no longer match the authoritative sequence')


def validate_metadata(root):
    contract = read_json(root / 'requirements/contracts.json')
    catalogue = read_json(root / 'verification/test-catalog.json')
    groups = validate_catalogue(root, catalogue)
    count = validate_requirements(root, contract, groups)
    validate_work_package_table(root, contract)
    validate_rollout(root, contract)
    text = (root / 'requirements/requirements.md').read_text()
    identifiers = re.findall(r'^\| (R\d{2}) \|', text, re.M)
    require(identifiers == [record['id'] for record in contract['requirements']],
            'Requirement table differs from canonical traceability')
    return count, groups


def heading_anchors(text):
    headings = re.findall(r'^#{1,6}\s+(.+?)\s*$', text, re.M)
    return {re.sub(r'[^\w\- ]', '', heading.lower()).replace(' ', '-') for heading in headings}


def check_link(file, reference, root):
    link = urlsplit(reference)
    if link.scheme:
        return
    target = (file.parent / unquote(link.path)).resolve() if link.path else file.resolve()
    require(target.is_relative_to(root.parent.resolve()), 'Documentation link escapes docs')
    require(target.is_file(), 'Broken local link in ' + str(file.relative_to(root)))
    if link.fragment:
        require(target.suffix == '.md' and unquote(link.fragment) in heading_anchors(target.read_text()),
                'Missing local heading anchor')


def validate_markdown(file, root):
    text = file.read_text()
    require(not any(line.rstrip() != line for line in text.splitlines()), 'Trailing whitespace')
    require(len(re.findall(r'^```', text, re.M)) % 2 == 0, 'Unbalanced Markdown fence')
    visible = re.sub(r'^```[^\n]*\n.*?^```\s*$', '', text, flags=re.M | re.S)
    headings = re.findall(r'^#{1,6}\s+(.+)$', visible, re.M)
    require(len(headings) == len(set(headings)), 'Duplicate Markdown heading')
    for reference in re.findall(r'!?\[[^\]]*\]\(([^)]+)\)', visible):
        check_link(file, reference, root)


def validate_package(root=PACKAGE_ROOT):
    requirements, groups = validate_metadata(root)
    documents = sorted(root.rglob('*.md'))
    for file in documents:
        validate_markdown(file, root)
    for file in root.rglob('*.py'):
        compile(file.read_text(), str(file), 'exec')
    models = run_models()
    return {'result': 'pass', 'scope': 'documentation, Python syntax and finite specifications',
            'requirements': requirements, 'test_groups': len(groups),
            'case_contracts': sum(len(group['cases']) for group in groups.values()),
            'markdown_documents': len(documents), 'model_states': models,
            'specification_sha256': specification_digest(root),
            'application_runtime': 'not_run', 'production_qualification': 'blocked'}


def write_check_report(result):
    result['generated_at_utc'] = datetime.now(timezone.utc).isoformat()
    file = PACKAGE_ROOT / 'verification/current-checks.json'
    file.write_text(json.dumps(result, indent=2) + '\n')


def run_tool_tests():
    command = [sys.executable, '-m', 'unittest', 'discover', '-s',
               str(PACKAGE_ROOT / 'tools/tests'), '-v']
    environment = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    result = subprocess.run(command, text=True, capture_output=True, env=environment, timeout=60)
    require(result.returncode == 0, 'Verification-tool regression tests failed: ' + result.stderr)
    count = re.search(r'Ran (\d+) tests?', result.stderr)
    require(count is not None and int(count.group(1)) >= 31, 'Missing verifier regression coverage')
    return {'result': 'pass', 'test_count': int(count.group(1)),
            'scope': 'verification tools and model counterexamples; not application tests'}


def parse_arguments():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render-catalogue', action='store_true')
    parser.add_argument('--write-report', action='store_true')
    parser.add_argument('--run-tests', action='store_true')
    parser.add_argument('--check-examples', action='store_true')
    return parser.parse_args()


def main():
    arguments = parse_arguments()
    try:
        prepare_outputs(arguments)
        result = validate_package()
        result.update(optional_checks(arguments))
    except (ValidationError, OSError, ValueError, TypeError, KeyError, SyntaxError,
            IndexError, StopIteration, subprocess.SubprocessError) as error:
        result = {'result': 'failed', 'scope': 'planning package', 'reason': str(error)}
    if arguments.write_report:
        write_check_report(result)
    print(json.dumps(result, indent=2))
    return 0 if result['result'] == 'pass' else 1


def optional_checks(arguments):
    result = {}
    if arguments.run_tests:
        result['verification_tools'] = run_tool_tests()
    if arguments.check_examples:
        from check_examples import run_example_checks
        result['command_examples'] = run_example_checks()
    return result


def prepare_outputs(arguments):
    if arguments.render_catalogue:
        catalogue = read_json(PACKAGE_ROOT / 'verification/test-catalog.json')
        (PACKAGE_ROOT / 'verification/acceptance.md').write_text(catalogue_text(catalogue))
    if arguments.write_report:
        write_check_report({'result': 'running', 'application_runtime': 'not_run'})


if __name__ == '__main__':
    raise SystemExit(main())
